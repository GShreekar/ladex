/** Hands a URL to the browser's download manager, which streams it to disk. */
export function saveViaBrowser(url: string, filename: string): void {
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.style.display = 'none';
  document.body.appendChild(link);
  link.click();
  link.remove();
}
